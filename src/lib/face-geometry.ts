export const FACE_GRID_W = W;
export const FACE_GRID_H = H;

export interface VoxelTile {
  x: number; // world x
  y: number; // world y
  z: number; // world z (depth — brighter = closer)
  brightness: number;
  restX: number;
  restY: number;
  restZ: number;
  scatterX: number; // idle scatter offset
  scatterY: number;
  scatterZ: number;
}

const TILE_SPACING = 0.055; // world units between tile centers
const FACE_SCALE_X = 1.0;
const FACE_SCALE_Y = 1.3; // faces are taller than wide
const BRIGHTNESS_THRESHOLD = 0.03;

export function buildVoxelFace(): VoxelTile[] {
  const tiles: VoxelTile[] = [];

  for (let row = 0; row < H; row++) {
    for (let col = 0; col < W; col++) {
      const brightness = RAW_MAP[row * W + col] ?? 0;
      if (brightness < BRIGHTNESS_THRESHOLD) continue;

      // Center the face grid
      const nx = (col / (W - 1) - 0.5) * 2; // -1 to 1
      const ny = (row / (H - 1) - 0.5) * -2; // 1 to -1 (flip Y)

      const wx = nx * (W / 2) * TILE_SPACING * FACE_SCALE_X;
      const wy = ny * (H / 2) * TILE_SPACING * FACE_SCALE_Y;
      // Depth: brighter tiles push forward
      const wz = (brightness - 0.3) * 0.18;

      // Per-tile scatter — loose displacement for idle organic feel
      const scatterX = (Math.random() - 0.5) * 0.008;
      const scatterY = (Math.random() - 0.5) * 0.008;
      const scatterZ = (Math.random() - 0.5) * 0.004;

      tiles.push({
        x: wx,
        y: wy,
        z: wz,
        brightness,
        restX: wx,
        restY: wy,
        restZ: wz,
        scatterX,
        scatterY,
        scatterZ,
      });
    }
  }

  return tiles;
}
